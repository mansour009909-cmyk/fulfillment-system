"""
يقرأ ملف مخزون المنتجات الخارجي (نفس الملف المستخدم مع سكيل supplier-inventory-report)
ويستخرج ربط باركود الكتاب -> اسم المورد (الماركة) بعد تطبيق نفس قواعد تطبيع
أسماء الموردين المستخدمة بالسكيل — فقط الجزء المتعلق بهوية المورد لكل كتاب،
بدون منطق الضريبة أو مطابقة الأرصدة (غير ذي صلة بنظام الفولفيلمنت).

الاستخدام: python read_inventory_xlsx.py <input.xlsx> <output.json>
"""
import sys
import json
import pandas as pd

INPUT_PATH = sys.argv[1]
OUTPUT_PATH = sys.argv[2]

inv = pd.read_excel(INPUT_PATH)

# ---- جهات مستبعدة (ليست موردي كتب فعليين) — نفس قائمة السكيل ----
EXCLUDED_SUPPLIERS = {
    'Anthropic, PBC', 'English books', 'Guangzhou Youdasheng International Trade Co.,Ltd',
    'the arrow', 'الصاعدي للنقليات', 'المتجر الإلكتروني صفقات', 'شركة آيليكس لوجيستكس',
    'شركة الصخيرات للنقليات', 'شركة تمكين الدولية للأجهزة المنزلية',
    'شركة تموينات شوق عبدالعزيز مساعد الثقفي للمواد الغذائية', 'شركة خزائن حمراء للتجارة',
    'شركة دار الحجاز للتخليص والشحن', 'شركة سعودي ماركت للمواد الغذائية',
    'شركة محمد الوصابي للتجارة', 'شي ان', 'مؤسسة ثلاجة العينين للتجارة',
    'مؤسسة ثلاجة نبع الخير', 'مؤسسة قمة الممتاز للنقل البري', 'متاجر الخليج',
    'متجر منافس', 'مطابع الفرقان الحديثة للطباعة', 'شركة أبناء سليمان حمد السيف للنقل البري',
}

STOP_WORDS = {'دار', 'للنشر', 'والتوزيع', 'للطباعة', 'مؤسسة', 'شركة', 'مركز',
              'و', 'من', 'في', 'على', 'للكتب', 'التوزيع', 'النشر', 'الطباعة'}


def key_tokens(name):
    tokens = set(str(name).strip().split()) - STOP_WORDS
    return tokens if tokens else set(str(name).strip().split())


def smart_score(a, b):
    ta, tb = key_tokens(a), key_tokens(b)
    if not ta or not tb:
        return 0
    intersection = len(ta & tb)
    union = len(ta | tb)
    if union == 0:
        return 0
    return (intersection / union + intersection / max(len(ta), len(tb))) / 2


# ---- استبعاد الجهات غير الموردين قبل أي شيء ----
inv = inv[~inv['الماركة'].apply(
    lambda n: any(smart_score(n, ex) >= 0.7 or str(n).strip() == ex.strip() for ex in EXCLUDED_SUPPLIERS)
)].copy()

# ---- تصفية المنتجات الجاهزة فقط ----
inv = inv[inv['نوع المنتج'] == 'منتج جاهز'].copy()
if 'أسم المنتج' in inv.columns:
    inv.rename(columns={'أسم المنتج': 'اسم المنتج'}, inplace=True)
if 'الكمية المتوفرة' in inv.columns:
    inv.rename(columns={'الكمية المتوفرة': 'الكمية'}, inplace=True)
inv['الماركة'] = inv['الماركة'].astype(str).str.strip()
inv['اسم المنتج'] = inv['اسم المنتج'].astype(str).str.strip()

# ---- أ. كتب موردين محددين بعناوين صريحة ----
inv.loc[inv['اسم المنتج'].isin({'نسران'}), 'الماركة'] = 'الآداب ملهمون'
inv.loc[inv['اسم المنتج'].isin({
    'رحلتي مع العشرين شعور الجزء الأول', 'رحلتي مع العشرين شعور الجزء الثاني',
}), 'الماركة'] = 'إيناس'
inv.loc[inv['اسم المنتج'].isin({
    'مقدمة ابن خلدون', 'الروح', 'رياض الصالحين من كلام سيد المرسلين',
    'الداء والدواء', 'الرحيق المختوم',
}), 'الماركة'] = 'ريما الشرق'
inv.loc[inv['اسم المنتج'].isin({'صناعة الولاء في قلوب العملاء'}), 'الماركة'] = 'سعد القحطاني'
inv.loc[inv['اسم المنتج'].isin({
    'الامير سيف الدين ونساؤه الاربعون', 'فروسية قفز الحواجز في المملكة',
}), 'الماركة'] = 'عبير'

# ---- ب. كتب عصير الكتب ----
aseer_books = {
    'الطفلة إيمان الجزء الأول', 'الطفلة إيمان الجزء الثاني',
    'الهاربة سارة - في داخل الأوراق كواليس موثقة لأحداث لا تصدق',
    'سارقة الأزواج - بداخل الاحداث ضحايا انتقام من امرأة خطيرة قد تكون منهم',
    'زيارات ليلية وقصص أخرى من عالم الإثارة والغموض', 'قصص لا يسمحون لي بنشرها',
    'متحف الأرواح - أسرار عائلة كويتية', 'جرعة زائدة - من الغموض والغرابة والمفاجآت',
    'حكايات من العالم الآخر',
    'حالات نادرة 1 - قصص غريبة تدور أحداثها حول مراهقات كويتيات',
    'حالات نادرة 2 - قصص غريبة تدور أحداثها حول مراهقات كويتيات',
    'حالات نادرة 3 - قصص غريبة تدور أحداثها حول مراهقات كويتيات',
    'في الجانب المظلم - ليلة لن تنساها أبدا', 'المعقد - رواية غريبة .... غريبة جدا',
    'حالات نادرة 5 - قصص غريبة تدور أحداثها حول فتيات كويتيات',
    'غرفة 722 - مجموعة قصصية طبية', 'حشرجة', 'ملاذ - الصندوق الأسود للبنات', 'ملاذ 2',
    '18 قصة غريبة', '17 قصة غريبة', 'مخلوقات الليل', 'القصر المهجور',
    'مخلوقات الليل الجزء الثاني', 'الحجرة الغامضة', 'تحت الأنقاض', 'سقم', 'المتلبس',
    'كتاب خالد - شخص عادي .. حياة غير عادية', 'جراب الحاوي', 'تقاسم الغنائم',
    'حالات نادرة 8', 'سر مذكرات الجورية الحمراء 3', 'سر مذكرات الجورية الحمراء 2', 'حالات نادرة 6.',
}
inv.loc[inv['اسم المنتج'].isin(aseer_books), 'الماركة'] = 'عصير الكتب'

# ---- ب٢. دمج صريح ----
inv.loc[inv['الماركة'] == 'الدار العربية للعلوم ناشرون', 'الماركة'] = 'شركة الدار العربية للعلوم ناشرون للنشر'
najma_variants = {v for v in inv['الماركة'].unique() if 'نجمة' in str(v)}
najma_variants.update({'دار نجمة القراء للنشر والتوزيع', 'نجمة القراء'})
inv.loc[inv['الماركة'].isin(najma_variants), 'الماركة'] = 'نجمة القراء'
inv.loc[inv['الماركة'].isin({'نورة', 'حكاية'}), 'الماركة'] = 'نورة حكاية'

# ---- ج. بيت الكتب للتجارة ----
bait_inv_brands = {
    'الآداب', 'الخيال', 'الساقي', 'الدار الأهلية', 'المدى', 'دور متنوعة',
    'ياض الريس', 'ممدوح بن عدوان', 'منشورات ضفاف', 'منشورات مقبرة الكتب',
    'وزيز', 'المركز الثقافي العربي', 'المؤسسة العربية للدراسات',
    'شغف', 'الوراق',
}
actual_brands = set(inv['الماركة'].unique())
bait_matched = {b for b in actual_brands for bb in bait_inv_brands if smart_score(b, bb) >= 0.7}
inv.loc[inv['الماركة'].isin(bait_matched), 'الماركة'] = 'بيت الكتب للتجارة'

# ---- د. أما بعد ----
ama_brands = {'أما بعد', 'مسكيلياني'}
ama_matched = {b for b in actual_brands for ab in ama_brands if smart_score(b, ab) >= 0.7}
inv.loc[inv['الماركة'].isin(ama_matched), 'الماركة'] = 'أما بعد'

# ---- تجهيز المخرجات ----
inv['رمز المنتج sku'] = inv['رمز المنتج sku'].astype(str).str.strip()
inv = inv[inv['رمز المنتج sku'].notna() & (inv['رمز المنتج sku'] != '') & (inv['رمز المنتج sku'] != 'nan')]
inv = inv[inv['الماركة'].notna() & (inv['الماركة'] != '') & (inv['الماركة'] != 'nan')]

before_dedup = len(inv)
inv = inv.drop_duplicates(subset=['رمز المنتج sku'], keep='first')
dupes_dropped = before_dedup - len(inv)

rows = [
    {'barcode': r['رمز المنتج sku'], 'title': r['اسم المنتج'], 'supplierName': r['الماركة']}
    for _, r in inv.iterrows()
]

with open(OUTPUT_PATH, 'w', encoding='utf-8') as f:
    json.dump(rows, f, ensure_ascii=False, indent=2)

print(f'كتب صالحة للاستيراد: {len(rows)}')
print(f'باركودات مكررة تم تجاهل تكرارها: {dupes_dropped}')
print(f'موردون مميّزون بعد التطبيع: {inv["الماركة"].nunique()}')
